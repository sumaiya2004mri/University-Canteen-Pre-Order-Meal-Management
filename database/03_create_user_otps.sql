-- Phase 3: Authentication redesign – MySQL OTP table
-- File: database/03_create_user_otps.sql
CREATE TABLE IF NOT EXISTS user_otps (
    otp_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL, -- references users(user_id)
    otp_hash VARCHAR(255) NOT NULL, -- bcrypt/argon2 hash of the 6‑digit OTP
    attempts INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_user_otps PRIMARY KEY (otp_id),
    CONSTRAINT fk_user_otps_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
    CONSTRAINT chk_otp_attempts CHECK (attempts >= 0)
);

-- Index for quick lookup by user_id and otp expiration
CREATE INDEX idx_user_otps_user_id ON user_otps(user_id);
CREATE INDEX idx_user_otps_expires_at ON user_otps(expires_at);
