-- ------------------------------------------------------------
-- 13_add_audit_tables.sql
-- Central audit tables for orders, menu, staff, reviews, payments
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS order_status_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    old_status VARCHAR(20),
    new_status VARCHAR(20) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    changed_by VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS menu_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id INT NOT NULL REFERENCES menu_items(item_id) ON DELETE CASCADE,
    action VARCHAR(20) NOT NULL,
    old_values JSONB,
    new_values JSONB,
    performed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    performed_by VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS staff_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    action VARCHAR(30) NOT NULL,
    details JSONB,
    performed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    performed_by VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS review_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT NOT NULL REFERENCES reviews(review_id) ON DELETE CASCADE,
    action VARCHAR(20) NOT NULL,
    performed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    performed_by VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS payment_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL REFERENCES payments(payment_id) ON DELETE CASCADE,
    event VARCHAR(30) NOT NULL,
    payload JSONB,
    performed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    performed_by VARCHAR(50) NOT NULL
);
