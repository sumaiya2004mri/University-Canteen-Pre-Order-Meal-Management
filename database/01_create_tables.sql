-- ----------------------------------------------------------------------------
-- 1. TABLE: users
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    user_id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    full_name       VARCHAR(100) NOT NULL,
    email           VARCHAR(100) NOT NULL,
    password_hash   VARCHAR(255) NOT NULL,
    phone           VARCHAR(20)  NULL,
    student_id      VARCHAR(50)  NULL,
    role            VARCHAR(20)  NOT NULL DEFAULT 'student',
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT uq_users_student_id UNIQUE (student_id),
    CONSTRAINT chk_users_role CHECK (role IN ('student', 'staff', 'canteen_staff', 'admin'))
);


-- ----------------------------------------------------------------------------
-- 2. TABLE: categories
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS categories (
    category_id     INT GENERATED BY DEFAULT AS IDENTITY,
    category_name   VARCHAR(50)  NOT NULL,
    description     VARCHAR(255) NULL,
    is_active       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_categories PRIMARY KEY (category_id),
    CONSTRAINT uq_categories_name UNIQUE (category_name)
);


-- ----------------------------------------------------------------------------
-- 3. TABLE: menu_items
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS menu_items (
    item_id         INT GENERATED BY DEFAULT AS IDENTITY,
    category_id     INT            NOT NULL,
    item_name       VARCHAR(100)   NOT NULL,
    description     TEXT           NULL,
    price           DECIMAL(10, 2) NOT NULL,
    stock_qty       INT            NOT NULL DEFAULT 0,
    is_available    BOOLEAN        NOT NULL DEFAULT TRUE,
    image_url       VARCHAR(255)   NULL,
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_menu_items PRIMARY KEY (item_id),
    CONSTRAINT fk_menu_items_category 
        FOREIGN KEY (category_id) REFERENCES categories (category_id) 
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_menu_items_price CHECK (price >= 0.00),
    CONSTRAINT chk_menu_items_stock CHECK (stock_qty >= 0)
);


-- ----------------------------------------------------------------------------
-- 4. TABLE: pickup_slots
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pickup_slots (
    slot_id         INT GENERATED BY DEFAULT AS IDENTITY,
    slot_date       DATE        NOT NULL,
    start_time      TIME        NOT NULL,
    end_time        TIME        NOT NULL,
    max_orders      INT         NOT NULL DEFAULT 30,
    is_active       BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_pickup_slots PRIMARY KEY (slot_id),
    CONSTRAINT uq_pickup_slot_window UNIQUE (slot_date, start_time, end_time),
    CONSTRAINT chk_slot_time_valid CHECK (end_time > start_time),
    CONSTRAINT chk_slot_max_orders CHECK (max_orders > 0)
);


-- ----------------------------------------------------------------------------
-- 5. TABLE: orders
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS orders (
    order_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT         NOT NULL,
    slot_id         INT            NOT NULL,
    order_status    VARCHAR(20)    NOT NULL DEFAULT 'pending',
    total_amount    DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    order_date      TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancelled_at    TIMESTAMPTZ    NULL     DEFAULT NULL,
    notes           VARCHAR(255)   NULL,
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_orders PRIMARY KEY (order_id),
    CONSTRAINT fk_orders_user 
        FOREIGN KEY (user_id) REFERENCES users (user_id) 
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_orders_slot 
        FOREIGN KEY (slot_id) REFERENCES pickup_slots (slot_id) 
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_orders_status CHECK (
        order_status IN ('pending', 'confirmed', 'preparing', 'ready', 'completed', 'cancelled')
    ),
    CONSTRAINT chk_orders_total CHECK (total_amount >= 0.00)
);


-- ----------------------------------------------------------------------------
-- 6. TABLE: order_items
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS order_items (
    order_item_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id        BIGINT         NOT NULL,
    item_id         INT            NOT NULL,
    quantity        INT            NOT NULL DEFAULT 1,
    unit_price      DECIMAL(10, 2) NOT NULL,
    subtotal        DECIMAL(10, 2) NOT NULL,

    CONSTRAINT pk_order_items PRIMARY KEY (order_item_id),
    CONSTRAINT fk_order_items_order 
        FOREIGN KEY (order_id) REFERENCES orders (order_id) 
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_order_items_item 
        FOREIGN KEY (item_id) REFERENCES menu_items (item_id) 
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT uq_order_item UNIQUE (order_id, item_id),
    CONSTRAINT chk_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT chk_order_items_unit_price CHECK (unit_price >= 0.00),
    CONSTRAINT chk_order_items_subtotal CHECK (subtotal >= 0.00)
);


-- ----------------------------------------------------------------------------
-- 7. TABLE: payments
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS payments (
    payment_id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id              BIGINT         NOT NULL,
    payment_method        VARCHAR(30)    NOT NULL DEFAULT 'cash',
    payment_status        VARCHAR(20)    NOT NULL DEFAULT 'unpaid',
    amount_paid           DECIMAL(10, 2) NOT NULL,
    transaction_reference VARCHAR(100)   NULL,
    payment_date          TIMESTAMPTZ    NULL     DEFAULT NULL,
    created_at            TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_payments PRIMARY KEY (payment_id),
    CONSTRAINT fk_payments_order 
        FOREIGN KEY (order_id) REFERENCES orders (order_id) 
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT uq_payments_transaction UNIQUE (transaction_reference),
    CONSTRAINT chk_payments_method CHECK (
        payment_method IN ('cash', 'card', 'bkash', 'nagad', 'online_banking', 'wallet')
    ),
    CONSTRAINT chk_payments_status CHECK (
        payment_status IN ('unpaid', 'pending', 'completed', 'failed', 'refunded')
    ),
    CONSTRAINT chk_payments_amount CHECK (amount_paid >= 0.00)
);
