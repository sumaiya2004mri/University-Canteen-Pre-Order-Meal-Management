CREATE TABLE IF NOT EXISTS pickup_slots (
    slot_id         INT GENERATED BY DEFAULT AS IDENTITY,
    slot_date       DATE        NOT NULL,
    start_time      TIME        NOT NULL,
    end_time        TIME        NOT NULL,
    max_orders      INT         NOT NULL DEFAULT 30,
    is_active       BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_pickup_slots PRIMARY KEY (slot_id),
    CONSTRAINT uq_pickup_slot_window UNIQUE (slot_date, start_time, end_time),
    CONSTRAINT chk_slot_time_valid CHECK (end_time > start_time),
    CONSTRAINT chk_slot_max_orders CHECK (max_orders > 0)
);
